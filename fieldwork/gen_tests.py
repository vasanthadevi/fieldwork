"""Turn a verified clean run into plain Playwright tests that need no AI."""

import argparse
import json
import os
import subprocess
from pathlib import Path

from .run import RUNS
from .servers import target_app

ROOT = Path(__file__).parent.parent
OUT = ROOT / "generated" / "answers.spec.ts"


def render(trace: dict) -> str:
    bad = [c["case"] for c in trace["checks"] if c["verdict"] != "pass"]
    if bad:
        raise ValueError(f"Refusing to generate tests from failing checks: {bad}")
    lines = ["// Generated by Fieldwork from a verified clean run. Do not edit by hand.",
             "import { expect, test } from '@playwright/test'", "",
             "const url = process.env.BUG ? `/?bug=${process.env.BUG}` : '/'", ""]
    for c in trace["checks"]:
        s = c["screen"]
        lines += [f"test({json.dumps(c['case'])}, async ({{ page }}) => {{",
                  "  await page.goto(url)",
                  f"  await page.getByTestId('query-input').fill({json.dumps(c['question'])})",
                  "  await page.getByTestId('query-input').press('Enter')",
                  "  const table = page.getByTestId('result-table')",
                  f"  await expect(table.locator('th')).toHaveText({json.dumps(s['columns'])})",
                  f"  await expect(table.locator('td')).toHaveText({json.dumps([x for r in s['rows'] for x in r])})",
                  f"  await expect(page.getByTestId('row-count')).toHaveText({json.dumps(s['rowBadge'])})",
                  f"  await expect(page.getByTestId('explanation')).toHaveText({json.dumps(s['explanation'])})",
                  "})", ""]
    return "\n".join(lines)


def generate() -> Path:
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(render(json.loads((RUNS / "clean" / "trace.json").read_text())))
    return OUT


def run_tests(bug: str | None) -> subprocess.CompletedProcess:
    return subprocess.run(["npx", "playwright", "test"], cwd=ROOT, capture_output=True, text=True,
                          env={**os.environ, "BUG": bug or ""})


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true", help="must pass clean and fail on a seeded bug")
    args = parser.parse_args()
    print(generate())
    if args.verify:
        with target_app():
            clean, seeded = run_tests(None), run_tests("rounded-values")
        print(clean.stdout[-300:], seeded.stdout[-300:])
        print("clean exit", clean.returncode, "| seeded exit", seeded.returncode)
        raise SystemExit(0 if clean.returncode == 0 and seeded.returncode != 0 else 1)


if __name__ == "__main__":
    main()
